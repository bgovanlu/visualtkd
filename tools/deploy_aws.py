"""Deploy site/ to AWS: S3 + CloudFront + ACM + Route 53 (infra/aws/site.yaml).

usage:
  python3 tools/deploy_aws.py              # update the stack, upload site/, invalidate the cache
  python3 tools/deploy_aws.py --stack      # stack only (first run, or after _redirects / infra changes)
  python3 tools/deploy_aws.py --content    # upload + invalidate only
  python3 tools/deploy_aws.py --render     # print the rendered template and stop

Uses the default AWS credentials (set AWS_PROFILE to pick others). The stack
lives in us-east-1 because CloudFront only takes certificates from there.

The /go/ short links come from site/_redirects (generated by build_form.py) and
are compiled into the CloudFront viewer-request function, so a changed or new
short link needs the stack step, not just an upload.
"""
import json, os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STACK = "visualtkd-site"
REGION = "us-east-1"
AWS = ["aws", "--region", REGION]

def go_links():
    links = {}
    for line in open(os.path.join(ROOT, "site/_redirects")):
        parts = line.split()
        if not parts or parts[0].startswith("#"):
            continue
        src, dest, code = parts
        assert src.startswith("/go/") and code == "302", f"unsupported redirect rule: {line.strip()}"
        links[src[4:]] = dest
    return links

def render():
    js = open(os.path.join(ROOT, "infra/aws/viewer-request.js")).read()
    js = js.replace("__GO__", json.dumps(go_links(), indent=2))
    assert len(js.encode()) < 10240, "CloudFront Functions are limited to 10 KB"
    tpl = open(os.path.join(ROOT, "infra/aws/site.yaml")).read()
    marker = "__VIEWER_REQUEST_JS__"
    line = next(l for l in tpl.splitlines() if l.strip() == marker)
    indent = line[: len(line) - len(line.lstrip())]
    body = "\n".join(indent + l if l else "" for l in js.rstrip("\n").splitlines())
    return tpl.replace(line, body)

def stack():
    with tempfile.NamedTemporaryFile("w", suffix=".yaml", delete=False) as f:
        f.write(render())
    try:
        print(f"deploying stack {STACK} (first run takes 5-15 min: certificate + distribution)")
        subprocess.check_call(AWS + ["cloudformation", "deploy", "--stack-name", STACK,
                                     "--template-file", f.name, "--no-fail-on-empty-changeset"])
    finally:
        os.unlink(f.name)

def outputs():
    out = subprocess.check_output(AWS + ["cloudformation", "describe-stacks", "--stack-name", STACK,
                                         "--query", "Stacks[0].Outputs", "--output", "json"])
    return {o["OutputKey"]: o["OutputValue"] for o in json.loads(out)}

def content():
    o = outputs()
    dest = f's3://{o["BucketName"]}'
    site = os.path.join(ROOT, "site")
    # PDFs and everything else first, so no page ever links to a file not yet uploaded.
    subprocess.check_call(AWS + ["s3", "sync", site, dest, "--delete", "--only-show-errors", "--exclude", "*.html",
                                 "--exclude", "_redirects", "--cache-control", "public, max-age=3600"])
    subprocess.check_call(AWS + ["s3", "sync", site, dest, "--delete", "--only-show-errors", "--exclude", "*", "--include", "*.html",
                                 "--content-type", "text/html; charset=utf-8",
                                 "--cache-control", "public, max-age=300"])
    inv = subprocess.check_output(AWS + ["cloudfront", "create-invalidation", "--distribution-id",
                                         o["DistributionId"], "--paths", "/*",
                                         "--query", "Invalidation.Id", "--output", "text"]).decode().strip()
    print(f"uploaded to {dest}; invalidation {inv} on {o['DistributionId']}")

if __name__ == "__main__":
    args = set(sys.argv[1:])
    if "--render" in args:
        sys.stdout.write(render())
        sys.exit()
    if "--content" not in args:
        stack()
    if "--stack" not in args:
        content()
