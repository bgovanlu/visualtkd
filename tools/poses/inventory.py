"""Inventory of distinct figure poses across the built forms.

A pose is what the figure looks like: view (front/side/back), facing (side views),
stance, lead foot, and what each arm does (an arm with no entry is chambered at
the hip). Two moves with the same pose share one image.

Mirroring: a pose and its left/right mirror image (lead foot and arms swapped,
side views facing the other way) can be drawn once and flipped. The count is
reported both ways.

usage: python3 tools/poses/inventory.py [--write]   (--write saves data/poses.json)
"""
import glob, json, os, sys, collections
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
O = {"L": "R", "R": "L", None: None}

def key(m):
    a = m.get("arms", {})
    face = m.get("face") if m["view"] == "side" else None
    return (m["view"], face, m["stance"], m.get("lead"), a.get("L", "chamber"), a.get("R", "chamber"))

def mirror(k):
    view, face, st, lead, al, ar = k
    return (view, O[face], st, O[lead], ar, al)

def canon(k):
    m = mirror(k)
    return min(k, m, key=lambda t: tuple("" if x is None else x for x in t))

def pid(k):
    view, face, st, lead, al, ar = k
    return "-".join(x for x in (st, f"lead{lead}" if lead else None, view, f"face{face}" if face else None, f"L{al}", f"R{ar}") if x)

def main():
    uses = collections.defaultdict(list)
    for p in sorted(glob.glob(os.path.join(ROOT, "forms/*.json"))):
        F = json.load(open(p))
        for m in F["moves"]:
            uses[key(m)].append(f'{F["slug"]}#{m["id"]}')
    exact = len(uses)
    canon_groups = collections.defaultdict(list)
    for k in uses: canon_groups[canon(k)].append(k)
    figures = sum(len(v) for v in uses.values())
    by_stance = collections.Counter(k[2] for k in canon_groups)
    by_view = collections.Counter(k[0] for k in canon_groups)
    print(f"figures on the boards: {figures}")
    print(f"distinct poses (exact):           {exact}")
    print(f"distinct poses (mirrors reused):  {len(canon_groups)}")
    print("by stance:", dict(sorted(by_stance.items(), key=lambda x: -x[1])))
    print("by view:  ", dict(by_view))
    if "--write" in sys.argv:
        out = []
        for c, ks in sorted(canon_groups.items(), key=lambda kv: pid(kv[0])):
            view, face, st, lead, al, ar = c
            out.append({"id": pid(c), "view": view, "face": face, "stance": st, "lead": lead,
                        "arms": {"L": al, "R": ar},
                        "mirror_of_uses": [pid(k) for k in ks if k != c],
                        "uses": sorted(u for k in ks for u in uses[k])})
        json.dump({"note": "Generated by tools/poses/inventory.py. One entry per distinct pose (mirror images share an entry).",
                   "count": len(out), "poses": out}, open(os.path.join(ROOT, "data/poses.json"), "w"), indent=1)
        print("-> data/poses.json")

if __name__ == "__main__":
    main()
